#!/usr/bin/env bash
# iFizBox's icons, all from one master: web/app/icons/icon.svg (flat, square; iOS 7+ masks the corners itself),
# itself built from tools/icon.svg.in and tools/icon_bg.py.
#
# Writes:
#   web/app/icons/icon-glossy.svg       the iOS 6 variant for places inside the app (Home header): the master with
#                                       iOS 6's rounded corners and gloss baked in
#   web/app/icons/icon-{180,192,512}.png  apple-touch-icon (180) and the web manifest (192, 512), flat
#   web/app/icons/icon-glossy-{76,152,228}.png  the glossy variant at the Home header's 76pt, 1x/2x/3x
#   native/icon/AppIcon60x60{,@2x,@3x}.png  the jailbreak app's home-screen icon (60/120/180), flat
#   web/app/icons/icon-web-{180,192,512,1024}.png  the website's home-screen icon (apple-touch-icon, manifest): a
#                                       blue WEB sash across the top-right corner, so it isn't taken for the app
#   web/app/icons/icon-web-glossy-{76,152,228}.png  the WEB icon with iOS 6 corners, for the website's Home header
#   native/icon/AppIconLite60x60{@2x,@3x}.png  the sideload IPA's icon: an orange LITE sash (red read as LIVE)
#                                       (the .deb keeps the plain one; native/build.sh picks)
#
# Needs rsvg-convert (librsvg). Run it after editing the master and commit what it writes.
set -euo pipefail
cd "$(dirname "$0")/.."
command -v rsvg-convert >/dev/null || { echo "icons: needs rsvg-convert (librsvg)" >&2; exit 1; }

dir=web/app/icons
master=$dir/icon.svg

# The master: the template with the generated starburst background embedded (it must be inline: an SVG shown as an
# <img> can't load other files).
command -v python3 >/dev/null || { echo "icons: needs python3 with numpy, scipy and Pillow" >&2; exit 1; }
bg=$(mktemp --suffix=.jpg)
trap 'rm -f "$bg"' EXIT
python3 -I tools/icon_bg.py "$bg" >/dev/null
python3 -I -c 'import base64,sys; t=open(sys.argv[1]).read(); b=base64.b64encode(open(sys.argv[2],"rb").read()).decode(); open(sys.argv[3],"w").write(t.replace("@BG@",b))' tools/icon.svg.in "$bg" "$master"

# Glossy variant: the master's drawing inside iOS 6's rounded square (corner radius 10/57 of the side, as the
# 57pt icon's mask). The shine is already in the master's background, so no extra gloss goes on top.
{
  echo '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
  echo '  <!-- Generated by tools/icons.sh from icon.svg: do not edit. iOS 6 corners and gloss for in-app use. -->'
  echo '  <defs>'
  echo '    <clipPath id="ios6-mask"><rect width="1024" height="1024" rx="180" ry="180"/></clipPath>'
  echo '    <linearGradient id="ios6-gloss" x1="0" y1="0" x2="0" y2="1">'
  echo '      <stop offset="0" stop-color="#fff" stop-opacity="0.62"/>'
  echo '      <stop offset="1" stop-color="#fff" stop-opacity="0.18"/>'
  echo '    </linearGradient>'
  echo '  </defs>'
  echo '  <g clip-path="url(#ios6-mask)">'
  # the master between its <svg> tags, comments dropped
  perl -0pe 's/<!--.*?-->\n?//gs; s/^.*?<svg[^>]*>\n//s; s/<\/svg>.*//s' "$master"
  # no gloss layer: the master has its shine built into the background (the original Cydia icon's look)
  echo '  </g>'
  echo '</svg>'
} > "$dir/icon-glossy.svg"

png() { rsvg-convert -w "$2" -h "$2" "$1" -o "$3"; }

for n in 180 192 512 1024; do png "$master" "$n" "$dir/icon-$n.png"; done

# Launch images for the home-screen app (apple-touch-startup-image), one per current iPhone screen: like Cydia's
# Default.png, the app's empty frame (nav bar, pinstripes, tab bar), drawn from the app's own CSS.
python3 tools/launch_images.py "$dir/launch" >/dev/null
# The Home header shows the glossy icon at 76pt: PNGs at 1x/2x/3x (Safari can draw an SVG <img> with an embedded
# picture at low resolution, which looked blurry and smeared on the phone).
for n in 76 152 228; do png "$dir/icon-glossy.svg" "$n" "$dir/icon-glossy-$n.png"; done
# sashed <text> <light colour> <dark colour>: the master with an iOS 6-style sash across the top-right corner (SVG on
# stdout), drawn like SpringBoard's "New" icon sash: a gradient along the sash, faint pinstripes across it, a light
# outer edge, a darker inner edge, a shadow on the icon, white text with a dark shadow above it.
sashed() {
  echo '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
  perl -0pe 's/<!--.*?-->\n?//gs; s/^.*?<svg[^>]*>\n//s; s/<\/svg>.*//s' "$master"
  cat <<SVG
  <defs>
    <linearGradient id="sash" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="$2"/><stop offset="1" stop-color="$3"/></linearGradient>
    <pattern id="sash-stripes" width="20" height="20" patternUnits="userSpaceOnUse">
      <rect width="10" height="20" fill="#fff" fill-opacity=".08"/><rect x="10" width="10" height="20" fill="#000" fill-opacity=".08"/>
    </pattern>
    <filter id="sash-shadow" x="-20%" y="-20%" width="140%" height="140%"><feDropShadow dx="0" dy="10" stdDeviation="9" flood-color="#000" flood-opacity=".6"/></filter>
    <filter id="sash-text" x="-10%" y="-30%" width="120%" height="160%"><feDropShadow dx="0" dy="-9" stdDeviation="0" flood-color="#000" flood-opacity=".45"/></filter>
  </defs>
  <g filter="url(#sash-shadow)"><g transform="translate(1024,0) rotate(45)">
    <rect x="-560" y="250" width="1120" height="250" fill="url(#sash)"/>
    <rect x="-560" y="250" width="1120" height="250" fill="url(#sash-stripes)"/>
    <rect x="-560" y="250" width="1120" height="8" fill="#fff" fill-opacity=".45"/>
    <rect x="-560" y="490" width="1120" height="10" fill="#000" fill-opacity=".3"/>
    <text x="0" y="428" text-anchor="middle" font-family="Helvetica Neue" font-weight="bold" font-size="150" letter-spacing="9" fill="#fff" filter="url(#sash-text)">$1</text>
  </g></g>
</svg>
SVG
}
web=$(mktemp --suffix=.svg) lite=$(mktemp --suffix=.svg)
trap 'rm -f "$bg" "$web" "$lite"' EXIT
sashed WEB '#4f8dff' '#0f47e8' > "$web"
sashed LITE '#ffa53b' '#e8660a' > "$lite"
for n in 180 192 512 1024; do png "$web" "$n" "$dir/icon-web-$n.png"; done
# The website's Home header shows the WEB icon too, glossy (iOS 6 corners) like icon-glossy-*.png.
webg=$(mktemp --suffix=.svg)
trap 'rm -f "$bg" "$web" "$lite" "$webg"' EXIT
{
  echo '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
  echo '<defs><clipPath id="ios6-mask"><rect width="1024" height="1024" rx="180" ry="180"/></clipPath></defs><g clip-path="url(#ios6-mask)">'
  perl -0pe 's/^.*?<svg[^>]*>\n//s; s/<\/svg>.*//s' "$web"
  echo '</g></svg>'
} > "$webg"
for n in 76 152 228; do png "$webg" "$n" "$dir/icon-web-glossy-$n.png"; done
# The sideload app's Home header shows its LITE icon the same way (user 2026-11-18).
liteg=$(mktemp --suffix=.svg)
trap 'rm -f "$bg" "$web" "$lite" "$webg" "$liteg"' EXIT
{
  echo '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
  echo '<defs><clipPath id="ios6-mask"><rect width="1024" height="1024" rx="180" ry="180"/></clipPath></defs><g clip-path="url(#ios6-mask)">'
  perl -0pe 's/^.*?<svg[^>]*>\n//s; s/<\/svg>.*//s' "$lite"
  echo '</g></svg>'
} > "$liteg"
for n in 76 152 228; do png "$liteg" "$n" "$dir/icon-lite-glossy-$n.png"; done
png "$lite" 120 native/icon/AppIconLite60x60@2x.png
png "$lite" 180 native/icon/AppIconLite60x60@3x.png

png "$master" 60 native/icon/AppIcon60x60.png
png "$master" 120 native/icon/AppIcon60x60@2x.png
png "$master" 180 native/icon/AppIcon60x60@3x.png
echo "icons: wrote $dir/icon-glossy.svg, the PNGs and $dir/launch/"
