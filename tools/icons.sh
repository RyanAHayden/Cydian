#!/usr/bin/env bash
# Cydian's icons, all from one master: web/app/icons/icon.svg (flat, square; iOS 7+ masks the corners itself).
#
# Writes:
#   web/app/icons/icon-glossy.svg       the iOS 6 variant for places inside the app (Home header): the master with
#                                       iOS 6's rounded corners and gloss baked in
#   web/app/icons/icon-{180,192,512}.png  apple-touch-icon (180) and the web manifest (192, 512), flat
#   web/app/icons/icon-glossy-{58,116,174}.png  the glossy variant at the Home header's 58pt, 1x/2x/3x
#   native/icon/AppIcon60x60{,@2x,@3x}.png  the native app's home-screen icon (60/120/180), flat
#
# Needs rsvg-convert (librsvg). Run it after editing the master and commit what it writes.
set -euo pipefail
cd "$(dirname "$0")/.."
command -v rsvg-convert >/dev/null || { echo "icons: needs rsvg-convert (librsvg)" >&2; exit 1; }

dir=web/app/icons
master=$dir/icon.svg

# Glossy variant: the master's drawing inside iOS 6's rounded square (corner radius 10/57 of the side, as the
# 57pt icon's mask), under the system's gloss: a white sheen over the top half with a curved lower edge.
{
  echo '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
  echo '  <!-- Generated by tools/icons.sh from icon.svg: do not edit. iOS 6 corners and gloss for in-app use. -->'
  echo '  <defs>'
  echo '    <clipPath id="ios6-mask"><rect width="1024" height="1024" rx="180" ry="180"/></clipPath>'
  echo '    <linearGradient id="ios6-gloss" x1="0" y1="0" x2="0" y2="1">'
  echo '      <stop offset="0" stop-color="#fff" stop-opacity="0.62"/>'
  echo '      <stop offset="1" stop-color="#fff" stop-opacity="0.18"/>'
  echo '    </linearGradient>'
  echo '  </defs>'
  echo '  <g clip-path="url(#ios6-mask)">'
  # the master between its <svg> tags, comments dropped
  perl -0pe 's/<!--.*?-->\n?//gs; s/^.*?<svg[^>]*>\n//s; s/<\/svg>.*//s' "$master"
  echo '    <path d="M0 0 H1024 V440 C760 500 264 500 0 440 Z" fill="url(#ios6-gloss)"/>'
  echo '  </g>'
  echo '</svg>'
} > "$dir/icon-glossy.svg"

png() { rsvg-convert -w "$2" -h "$2" "$1" -o "$3"; }

for n in 180 192 512; do png "$master" "$n" "$dir/icon-$n.png"; done
for n in 58 116 174; do png "$dir/icon-glossy.svg" "$n" "$dir/icon-glossy-$n.png"; done
png "$master" 60 native/icon/AppIcon60x60.png
png "$master" 120 native/icon/AppIcon60x60@2x.png
png "$master" 180 native/icon/AppIcon60x60@3x.png
echo "icons: wrote $dir/icon-glossy.svg, 9 PNGs"
