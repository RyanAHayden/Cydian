#!/usr/bin/env python3
"""The product's name for native/ and the Python tools (F170): native/brand.env read as a dict, and the files made
from it.

  python3 native/brand.py sync     after changing brand.env (and web/app/brand.js): regenerate sign/Brand.swift,
                                   and put BRAND_NAME in the web files that can't import brand.js (index.html,
                                   manifest.json) and in the AltStore source (web/app/source.json, tools/altsource.py)
  python3 native/brand.py NAME     print one value (BRAND_NAME, BRAND_DOMAIN, ...)

Python: `from brand import BRAND` with native/ on sys.path (tools/ add it, as they do for mkdeb/mkipa).
native/test_brand.py checks that all of these agree.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ENV = os.path.join(HERE, "brand.env")
SWIFT = os.path.join(HERE, "sign", "Brand.swift")
WEB = os.path.join(ROOT, "web", "app")


def load(path=ENV):
    out = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            k, _, v = line.partition("=")
            out[k.strip()] = v.strip().strip('"')
    return out


BRAND = load()
NAME = BRAND["BRAND_NAME"]


def swift(brand=BRAND):
    """sign/Brand.swift: in sign/ so every build and Swift test that compiles sign/*.swift has it."""
    name = brand["BRAND_NAME"].replace("\\", "\\\\").replace('"', '\\"')
    return ("// Generated by native/brand.py sync from native/brand.env (F170): do not edit.\n"
            "enum Brand {\n"
            f"    static let name = \"{name}\"\n"
            "}\n")


def html(text, name=NAME):
    """index.html's title and Open Graph names (crawlers read them without running JS)."""
    text = re.sub(r"<title>[^<]*</title>", f"<title>{name}</title>", text, count=1)
    for prop in ("og:site_name", "og:title"):
        text = re.sub(rf'(<meta property="{prop}" content=")[^"]*(")', rf"\g<1>{name}\g<2>", text, count=1)
    return re.sub(r'(<meta property="og:image:alt" content=")[^"\']*(\'s glossy icon)', rf"\g<1>{name}\g<2>", text, count=1)


def manifest(text, name=NAME):
    for key in ("name", "short_name"):
        text = re.sub(rf'("{key}": ")[^"]*(")', rf"\g<1>{name}\g<2>", text, count=1)
    return text


def _rewrite(path, fn):
    with open(path) as f:
        old = f.read()
    new = fn(old)
    if new != old:
        with open(path, "w") as f:
            f.write(new)
        print("brand: wrote", os.path.relpath(path, ROOT))


def sync():
    _rewrite(SWIFT, lambda _: swift())
    _rewrite(os.path.join(WEB, "index.html"), html)
    _rewrite(os.path.join(WEB, "manifest.json"), manifest)
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import altsource
    with open(altsource.SOURCE) as f:
        data = json.load(f)
    altsource.write(altsource.rebrand(data))


if __name__ == "__main__":
    if sys.argv[1:] == ["sync"]:
        if not os.path.exists(SWIFT):
            open(SWIFT, "w").close()
        sync()
    elif len(sys.argv) == 2 and sys.argv[1] in BRAND:
        print(BRAND[sys.argv[1]])
    else:
        print(__doc__.strip(), file=sys.stderr)
        sys.exit(2)
